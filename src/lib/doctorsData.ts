/**
 * Normalizes city names to handle spelling variants (e.g. Allahabad -> Prayagraj, Banaras/Kashi -> Varanasi).
 */
export function normalizeCityName(cityInput?: string | null): string {
  if (!cityInput) return "";
  const cleaned = cityInput.trim().toLowerCase();
  if (!cleaned) return "";

  if (
    cleaned.includes("prayag") ||
    cleaned.includes("allahabad") ||
    cleaned.includes("ilhabad")
  ) {
    return "Prayagraj";
  }

  if (
    cleaned.includes("lucknow") ||
    cleaned === "lko" ||
    cleaned.includes("lucknow city")
  ) {
    return "Lucknow";
  }

  if (
    cleaned.includes("varanasi") ||
    cleaned.includes("banaras") ||
    cleaned.includes("benares") ||
    cleaned.includes("kashi")
  ) {
    return "Varanasi";
  }

  if (cleaned.includes("agra")) {
    return "Agra";
  }

  if (
    cleaned.includes("gorakhpur") ||
    cleaned === "gkp"
  ) {
    return "Gorakhpur";
  }

  return cityInput.trim();
}
